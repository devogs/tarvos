#!/usr/bin/env python3
"""Render the lldpd configuration from the environment.

lldpd reads ``/etc/lldpd.d/*.conf`` (lldpcli syntax) at startup. Every value is validated
against a strict character set before being rendered, so nothing from the environment can
inject extra lldpcli commands. Exit status: 0 = start lldpd, 10 = LLDP disabled (do not
start it), 1 = could not write the configuration.
"""

from __future__ import annotations

import os
import re
import socket
import sys
from dataclasses import dataclass
from pathlib import Path

from tarvos_common import ConfigError, parse_choice, parse_int
from tarvos_common import log as _log

EXIT_DISABLED = 10
DEFAULT_INTERFACES = "*"
DEFAULT_DESCRIPTION = "Tarvos Network OS"
# lldpd interface patterns: names, shell-style wildcards, "!" exclusions, comma separated.
INTERFACE_PATTERN = re.compile(r"[A-Za-z0-9_.:*?!,-]{1,128}")
SYSTEM_NAME = re.compile(r"[A-Za-z0-9_.-]{1,64}")
SYSTEM_DESCRIPTION = re.compile(r"[A-Za-z0-9 _.,:/()+-]{1,200}")


def log(message: str) -> None:
    _log("lldp", message)


@dataclass(frozen=True)
class LldpSettings:
    enabled: bool
    interfaces: str
    tx_interval: int
    tx_hold: int
    system_name: str
    description: str


def _parse_text(name: str, value: str | None, default: str, pattern: re.Pattern[str]) -> str:
    if value is None or not value.strip():
        return default
    text = value.strip()
    if not pattern.fullmatch(text):
        raise ConfigError(f"{name} contains unsupported characters or is too long")
    return text


def load_settings(env: dict[str, str], hostname: str = "tarvos") -> LldpSettings:
    """Build settings; invalid input is logged and LLDP stays off rather than half-configured."""
    disabled = LldpSettings(False, DEFAULT_INTERFACES, 30, 4, hostname, DEFAULT_DESCRIPTION)
    try:
        enabled = parse_choice("LLDP_ENABLED", env.get("LLDP_ENABLED"), "yes", ("yes", "no"))
        if enabled == "no":
            return disabled
        return LldpSettings(
            enabled=True,
            interfaces=_parse_text(
                "LLDP_INTERFACES", env.get("LLDP_INTERFACES"), DEFAULT_INTERFACES, INTERFACE_PATTERN
            ),
            tx_interval=parse_int("LLDP_TX_INTERVAL", env.get("LLDP_TX_INTERVAL"), 30, 1, 3600),
            tx_hold=parse_int("LLDP_TX_HOLD", env.get("LLDP_TX_HOLD"), 4, 1, 100),
            system_name=_parse_text(
                "LLDP_SYSTEM_NAME", env.get("LLDP_SYSTEM_NAME"), hostname, SYSTEM_NAME
            ),
            description=_parse_text(
                "LLDP_SYSTEM_DESCRIPTION",
                env.get("LLDP_SYSTEM_DESCRIPTION"),
                DEFAULT_DESCRIPTION,
                SYSTEM_DESCRIPTION,
            ),
        )
    except ConfigError as exc:
        log(f"ERROR: {exc}; LLDP disabled")
        return disabled


def render(settings: LldpSettings) -> str:
    return (
        "\n".join(
            [
                "# Generated by Tarvos lldp_configure.py - do not edit",
                f"configure system hostname {settings.system_name}",
                f'configure system description "{settings.description}"',
                f'configure system interface pattern "{settings.interfaces}"',
                f"configure lldp tx-interval {settings.tx_interval}",
                f"configure lldp tx-hold {settings.tx_hold}",
            ]
        )
        + "\n"
    )


def main() -> int:
    root = Path(os.environ.get("TARVOS_ROOT", "/"))
    settings = load_settings(dict(os.environ), socket.gethostname().split(".")[0] or "tarvos")
    if not settings.enabled:
        log("LLDP disabled")
        return EXIT_DISABLED
    target = root / "etc/lldpd.d/tarvos.conf"
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render(settings))
        target.chmod(0o644)
    except OSError as exc:
        log(f"FATAL: {exc}")
        return 1
    log(
        f"enabled on '{settings.interfaces}' (interval {settings.tx_interval}s, "
        f"hold {settings.tx_hold}, system name {settings.system_name})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
