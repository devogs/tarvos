#!/usr/bin/env python3
"""Render AAA configuration (sshd, PAM, nsswitch, admin account) from the environment.

12-factor: every input comes from environment variables (see .env.example).
Security: server addresses are validated with ``ipaddress``; the TACACS+ secret is
restricted to a safe character set, never logged, and written only to 0600 files.
Any TACACS+ misconfiguration degrades to local-only authentication (``admin``).
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

from tarvos_common import ConfigError, parse_choice, parse_int, parse_ip_list
from tarvos_common import log as _log

ADMIN_USER = "admin"
DEFAULT_ADMIN_PASSWORD = "admin"  # noqa: S105 - documented lab default, overridable via env
TACACS_USER = "tacacs"
TACACS_UID = 1001
TACACS_GID = 1001
MAX_SERVERS = 4
# Built from source (not packaged in Debian trixie), so referenced by absolute path.
PAM_TACPLUS_MODULE = "/usr/local/lib/security/pam_tacplus.so"

_SECRET_RE = re.compile(r"^[\x21-\x7e]{1,128}$")  # printable ASCII, no whitespace
_LOG_LEVELS = {"debug": "DEBUG", "info": "INFO", "warning": "INFO", "error": "ERROR"}


def log(message: str) -> None:
    _log("aaa", message)


# --------------------------------------------------------------------------- parsing
def parse_tacacs_servers(raw: str | None) -> list[str]:
    """Parse ``TACACS_SERVER`` into a validated, ordered, de-duplicated IP list."""
    return parse_ip_list(raw, "TACACS_SERVER", MAX_SERVERS)


def validate_secret(secret: str | None) -> str:
    if not secret or not _SECRET_RE.match(secret):
        raise ConfigError("TACACS_SECRET must be 1-128 printable characters without spaces")
    return secret


def parse_yes_no(name: str, value: str | None, default: str) -> str:
    return parse_choice(name, value, default, ("yes", "no"))


# --------------------------------------------------------------------------- settings
@dataclass(frozen=True)
class AaaSettings:
    servers: tuple[str, ...]
    secret: str
    timeout: int

    @property
    def tacacs_enabled(self) -> bool:
        return bool(self.servers)


def load_settings(env: dict[str, str]) -> AaaSettings:
    """Build settings; on any TACACS+ error log it and fall back to local-only."""
    try:
        servers = parse_tacacs_servers(env.get("TACACS_SERVER"))
        timeout = parse_int("TACACS_TIMEOUT", env.get("TACACS_TIMEOUT"), 3, 1, 30)
        secret = validate_secret(env.get("TACACS_SECRET")) if servers else ""
    except ConfigError as exc:
        log(f"ERROR: {exc}; TACACS+ disabled, local '{ADMIN_USER}' only")
        return AaaSettings((), "", 3)
    return AaaSettings(tuple(servers), secret, timeout)


# --------------------------------------------------------------------------- rendering
def render_pam(settings: AaaSettings, *, with_session: bool) -> str:
    """PAM stack. ``admin`` is a break-glass account that never waits on TACACS+."""
    lines = ["# Generated by Tarvos aaa_configure.py - do not edit"]
    skip_admin = (
        f"[success=1 default=ignore] pam_succeed_if.so quiet user = {ADMIN_USER}"
    )
    if settings.tacacs_enabled:
        servers = " ".join(f"server={s}" for s in settings.servers)
        tac = (
            f"{PAM_TACPLUS_MODULE} {servers} secret={settings.secret} "
            f"timeout={settings.timeout} service=shell protocol=ssh login=pap encrypt"
        )
        lines += [
            f"auth {skip_admin}",
            f"auth sufficient {tac}",
            "auth required pam_unix.so",
            f"account {skip_admin}",
            f"account sufficient {tac}",
            "account required pam_unix.so",
        ]
    else:
        lines += ["auth required pam_unix.so", "account required pam_unix.so"]
    if with_session:
        lines += [
            "session required pam_limits.so",
            "session required pam_unix.so",
            "session optional pam_env.so",
        ]
    return "\n".join(lines) + "\n"


def render_sshd(env: dict[str, str]) -> str:
    port = parse_int("SSH_PORT", env.get("SSH_PORT"), 22, 1, 65535)
    root = parse_yes_no("SSH_PERMIT_ROOT_LOGIN", env.get("SSH_PERMIT_ROOT_LOGIN"), "no")
    password = parse_yes_no("SSH_PASSWORD_AUTH", env.get("SSH_PASSWORD_AUTH"), "yes")
    level = _LOG_LEVELS.get((env.get("LOG_LEVEL") or "info").lower(), "INFO")
    return (
        "# Generated by Tarvos aaa_configure.py - do not edit\n"
        f"Port {port}\n"
        f"PermitRootLogin {root}\n"
        f"PasswordAuthentication {password}\n"
        "KbdInteractiveAuthentication no\n"
        "UsePAM yes\n"
        "PermitEmptyPasswords no\n"
        "X11Forwarding no\n"
        f"LogLevel {level}\n"
    )


def render_nsswitch(current: str, *, tacacs_enabled: bool) -> str:
    """Add/remove the ``ato`` NSS source on the passwd line (idempotent).

    With TACACS+ enabled, unknown usernames resolve to the shared ``tacacs`` account
    so that users authenticated remotely can obtain a local session.
    """
    out = []
    for line in current.splitlines():
        if line.startswith("passwd:"):
            sources = [s for s in line.split(":", 1)[1].split() if s != "ato"]
            if tacacs_enabled:
                sources.append("ato")
            line = "passwd:         " + " ".join(sources)
        out.append(line)
    return "\n".join(out) + "\n"


def render_ato_conf() -> str:
    return (
        f"{TACACS_USER}:x:{TACACS_UID}:{TACACS_GID}:Tarvos TACACS+ user:"
        f"/home/{TACACS_USER}:/bin/bash\n"
    )


# --------------------------------------------------------------------------- side effects
def write_file(root: Path, path: str, content: str, mode: int) -> None:
    target = root / path.lstrip("/")
    target.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "w") as handle:
        handle.write(content)
    os.chmod(target, mode)


def set_admin_password(password: str) -> None:
    if not password or any(c in password for c in "\n\r\x00"):
        raise ConfigError("ADMIN_PASSWORD must be non-empty and single-line")
    if password == DEFAULT_ADMIN_PASSWORD:
        log("WARNING: default 'admin' password in use; set ADMIN_PASSWORD outside labs")
    subprocess.run(
        ["chpasswd"], input=f"{ADMIN_USER}:{password}\n", text=True, check=True
    )


def configure(env: dict[str, str], root: Path, *, set_password: bool = True) -> AaaSettings:
    settings = load_settings(env)
    if set_password:
        set_admin_password(env.get("ADMIN_PASSWORD") or DEFAULT_ADMIN_PASSWORD)

    # PAM files carry the TACACS+ secret in module arguments: root-only, 0600.
    write_file(root, "/etc/pam.d/sshd", render_pam(settings, with_session=True), 0o600)
    # libnetconf2 opens the PAM service named "netopeer2.conf" (not "netopeer2")
    write_file(root, "/etc/pam.d/netopeer2.conf", render_pam(settings, with_session=False), 0o600)
    write_file(root, "/etc/ssh/sshd_config.d/10-tarvos.conf", render_sshd(env), 0o644)

    nsswitch = root / "etc/nsswitch.conf"
    current = nsswitch.read_text() if nsswitch.exists() else "passwd: files\n"
    write_file(
        root,
        "/etc/nsswitch.conf",
        render_nsswitch(current, tacacs_enabled=settings.tacacs_enabled),
        0o644,
    )
    if settings.tacacs_enabled:
        write_file(root, "/etc/libnss-ato.conf", render_ato_conf(), 0o644)
        log(f"TACACS+ enabled, servers: {', '.join(settings.servers)}")
    else:
        log(f"TACACS+ not configured; local '{ADMIN_USER}' authentication only")
    return settings


def main() -> int:
    root = Path(os.environ.get("TARVOS_ROOT", "/"))
    try:
        configure(dict(os.environ), root, set_password=root == Path("/"))
    except (ConfigError, OSError, subprocess.CalledProcessError) as exc:
        log(f"FATAL: {exc}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
